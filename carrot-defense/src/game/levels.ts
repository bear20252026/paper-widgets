/** 每章 25 关,共 100 关。 */
export const CHAPTER_SIZE = 25;
export const CLASSIC_COUNT = CHAPTER_SIZE;
export const CH2_END = CHAPTER_SIZE * 2;
export const CH3_END = CHAPTER_SIZE * 3;
export const CH4_END = CHAPTER_SIZE * 4;

const HAND_SPLIT: Record<number, LevelDraft[]> = {
  1: RAW.slice(0, 13),
  2: RAW.slice(13, 25),
  3: RAW.slice(25, 37),
  4: RAW.slice(37),
};

/** 按章组装:手工关卡 + 生成关卡,每章补足 25 关。 */
export const LEVELS: LevelDef[] = (() => {
  const out: LevelDef[] = [];
  for (const chapter of [1, 2, 3, 4] as const) {
    const hand = HAND_SPLIT[chapter];
    const drafts: LevelDraft[] = [...hand];
    const need = CHAPTER_SIZE - hand.length;
    if (need > 0) {
      drafts.push(...generateChapterLevels(chapter, need, drafts.length + out.length));
    }
    for (const d of drafts) {
      const id = out.length + 1;
      out.push({
        ...d,
        id,
        cols: d.cols ?? 12,
        rows: d.rows ?? 8,
        chapter,
        obstacles: d.obstacles as ObstacleSpawn[],
        waves: generateWaves(d.waves),
      });
    }
  }
  return out;
})();

export function getLevel(id: number): LevelDef {
  return LEVELS.find((l) => l.id === id) ?? LEVELS[0];
}

