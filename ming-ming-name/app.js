function resolveKey(s){
 s = s.toLowerCase();
 if(BANK[s]) return s;
 if(ALIAS[s] && BANK[ALIAS[s]]) return ALIAS[s];
 let t = s;
 while(t.length > 1){
   t = t.slice(0,-1);
   if(BANK[t]) return t;
   if(ALIAS[t] && BANK[ALIAS[t]]) return ALIAS[t];
 }
 return LETTER_DEF[s[0]] || "yi";
}
function syllabify(w){
 w = w.toLowerCase().replace(/[^a-z]/g,"");
 if(!w) return [];
 const m = w.match(/[^aeiouy]*[aeiouy]+(?:[^aeiouy](?![aeiouy]))?/g);
 return m && m.length ? m : [w];
}
function buildName(){
 const raw = state.raw.trim();
 if(!raw){ state.surname=null; state.slots=[]; renderAll(); return; }
 const parts = raw.split(/\s+/);
 const given = parts[0];
 const surWord = parts.length>1 ? parts[parts.length-1] : null;
 if(surWord){
   const k = surWord.toLowerCase().replace(/[^a-z]/g,"");
   state.surname = SURNAMES[k] || SUR_LETTER[k[0]] || "安";
   state.surFrom = surWord;
 } else { state.surname = null; state.surFrom = ""; }
 let keys, stdChars = null;
 const gk = given.toLowerCase().replace(/[^a-z]/g,"");
 if(!surWord && STD[gk]){
   /* a name on its own: give the spelling people expect, then let it be tuned */
   stdChars = [...STD[gk][0]];
   keys = STD[gk][1].split(" ");
 } else if(NAMES[gk]) keys = NAMES[gk].slice();
 else {
   const syl = syllabify(gk).map(resolveKey);
   keys = surWord ? syl.slice(0,2) : syl.slice(0,4);
 }
 if(keys.length===1 && !stdChars) keys.push("ran");
 if(keys.length===0) keys=["mo","ran"];
 /* which letters of what they typed does each character stand for? */
 const syls = syllabify(gk);
 const spans = [];
 if(syls.length===keys.length && /^[a-z]+$/i.test(given)){
   let at = 0;
   syls.forEach(s=>{ spans.push([at, at+s.length]); at += s.length; });
 }
 state.slots = keys.map((k,i)=>{
   const key = BANK[k] ? k : resolveKey(k);
   const opts = BANK[key].map(o=>o.slice());
   if(stdChars && stdChars[i]){
     const sc = stdChars[i];
     const at = opts.findIndex(o=>o[0]===sc);
     if(at>=0) opts.unshift(opts.splice(at,1)[0]);
     else opts.unshift([sc, CONV[sc] || "used in the standard spelling"]);
   }
   return {key, opts, sel:0, span:spans[i]||null};
 });
 state.activeSlot = 0; state.openSrc = -1;
 state.std = stdChars ? STD[gk][0] : null;
 state.givenWord = given;
 renderAll();
}
