   lfo.frequency.value = 3+Math.random()*2; lg.gain.value = 70;
   lfo.connect(lg).connect(f.frequency);
   const g = this.ctx.createGain();
   g.gain.setValueAtTime(0, t);
   g.gain.linearRampToValueAtTime(.009+Math.random()*.004, t+.14);
   src.connect(f).connect(g).connect(this.ctx.destination);
   src.start(t); lfo.start(t);
   src.stop(t+2.5); lfo.stop(t+2.5);      // backstop if a rerender orphans the stroke
