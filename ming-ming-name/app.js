/* material tiles: seamless value-noise treated as a HEIGHT MAP and lit from the
   upper left, so bumps genuinely catch the light (the felt-lab technique).
   mode "solid" bakes a coloured surface; mode "neutral" bakes a mid-grey relief
   layer for blending over any paper colour with soft-light. */
function makeLitTile(p, mode, seed0){
 const S = 256;
 let seed = seed0;
 const rnd = ()=>{ seed = (seed*1664525 + 1013904223) >>> 0; return seed/4294967296; };
 const hc = document.createElement("canvas"); hc.width = hc.height = S;
 const hg = hc.getContext("2d");
 hg.fillStyle = "#808080"; hg.fillRect(0,0,S,S);
 hg.imageSmoothingEnabled = true; hg.imageSmoothingQuality = "high";
 const lowW = p.cloud/100, hiW = p.fine/100;
 const OCT = [
   [3, lowW*.6],[6, lowW*.48],[12, lowW*.32],
   [32, hiW*.42],[64, hiW*.32],[128, hiW*.24]
 ];
 OCT.forEach(([n,w])=>{
   if(w<=0.005) return;
   const t = document.createElement("canvas"); t.width = t.height = n;
   const tg = t.getContext("2d"), im = tg.createImageData(n,n);
   for(let i=0;i<n*n;i++){
     const v = Math.round(128 + (rnd()-.5)*150);
     im.data[i*4]=im.data[i*4+1]=im.data[i*4+2]=v; im.data[i*4+3]=255;
   }
   tg.putImageData(im,0,0);
   const t3 = document.createElement("canvas"); t3.width = t3.height = n*3;
   const t3g = t3.getContext("2d");
   for(let a=0;a<3;a++) for(let b=0;b<3;b++) t3g.drawImage(t, a*n, b*n);
   hg.globalAlpha = Math.min(1,w);
   /* centre tile of a 3×3 repeat: edge interpolation reads the neighbours,
      so the upscaled cloud wraps perfectly */
   hg.drawImage(t3, n, n, n, n, 0, 0, S, S);
 });
 hg.globalAlpha = 1;
 const H = hg.getImageData(0,0,S,S).data;
 const warm = (p.warm||45)/100;
 const solid = mode==="solid";
 /* soft-light darkens more than it lightens on pale grounds, so the neutral
    tile sits a touch above mid-grey to come out colour-true */
 const mid = 128 + (p.lift||0);
 const br = solid ? 241+Math.round(warm*4-2) : mid;
 const bg_ = solid ? 239+Math.round(warm*2-1) : mid;
 const bb = solid ? 233-Math.round(warm*6-3) : mid;
 const c = document.createElement("canvas"); c.width = c.height = S;
 const g = c.getContext("2d");
 const out = g.createImageData(S,S);
 const kR = p.relief/100*1.9, kL = p.ctr/100*.42;
 for(let y=0;y<S;y++){
   const yu = (y-1+S)%S;
   for(let x=0;x<S;x++){
     const i = y*S+x, xu = (x-1+S)%S;
     const h = H[i*4];
     const d = (h - H[(yu*S+xu)*4])*kR + (h-128)*kL;
     const o = i*4;
     out.data[o]   = Math.max(0,Math.min(255, br + d));
     out.data[o+1] = Math.max(0,Math.min(255, bg_ + d));
     out.data[o+2] = Math.max(0,Math.min(255, bb + d*.92));   // shadows stay warm
     out.data[o+3] = 255;
   }
 }
 g.putImageData(out,0,0);
 return c;
}
