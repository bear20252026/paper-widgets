/* ── INKBRUSH · stroke animation for the hands hanzi-writer cannot write (行/草/隶).
   the font's own glyph is rasterised → thinned to a skeleton → the skeleton's
   distance to the glyph edge becomes brush pressure → pieces are ordered by
   the kai stroke order (hanzi-writer medians; position-first claiming; never
   upward; above-before-below within a column) → a brush sweeps a MASK along
   them and the real glyph shows through wherever it has been. what is written
   is what stays. developed in lab.html; keep the two in step. ── */
