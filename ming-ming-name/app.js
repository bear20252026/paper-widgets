   const src = this.ctx.createBufferSource(); src.buffer = this.buf;
   const f = this.ctx.createBiquadFilter();
   f.type = "lowpass"; f.frequency.setValueAtTime(600+Math.random()*250, t); f.Q.value = .5;
   const g = this.ctx.createGain();
