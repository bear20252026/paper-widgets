export const formatCNY = (fen: number): string =>
  new Intl.NumberFormat('zh-CN', {
    style: 'currency',
    currency: 'CNY',
    minimumFractionDigits: 2,
  }).format(fen / 100);

export const formatCNYCompact = (fen: number): string => {
  const yuan = fen / 100;
  if (Math.abs(yuan) >= 100000000) return `¥${(yuan / 100000000).toFixed(2)}亿`;
  if (Math.abs(yuan) >= 10000) return `¥${(yuan / 10000).toFixed(1)}万`;
  return `¥${yuan.toLocaleString('zh-CN', { maximumFractionDigits: 0 })}`;
};

export const maskPhone = (phone: string): string => phone.replace(/(\d{3})\d{4}(\d{4})/, '$1****$2');

export const avatarTone = (seed: string): string => {
  const tones = [
    'bg-slate-900 text-white',
    'bg-orange-500 text-white',
    'bg-emerald-600 text-white',
    'bg-sky-600 text-white',
    'bg-violet-600 text-white',
    'bg-rose-500 text-white',
    'bg-amber-500 text-white',
  ];
  let hash = 0;
  for (let i = 0; i < seed.length; i += 1) hash = (hash * 31 + seed.charCodeAt(i)) % 997;
  return tones[hash % tones.length];
};

